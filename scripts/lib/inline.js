/**
 * Turns src/*.js modules into self-contained snippets for n8n Code nodes.
 * Each module becomes `const NAME = (() => { const module = { exports: {} }; ... ; return module.exports; })();`
 */
const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, '..', '..', 'src');

function inlineModule(file, name) {
  const code = fs.readFileSync(path.join(SRC, file), 'utf8');
  const noComments = code.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');
  if (/\brequire\(/.test(noComments)) throw new Error(`${file} must not call require() - it is inlined into n8n`);
  return `const ${name} = (() => {\nconst module = { exports: {} };\n${code}\nreturn module.exports;\n})();\n`;
}

/** modules: [['scoring.js','S'], ['templates.js','T']] ; body: the node-specific code */
function codeNode(modules, body) {
  const header = '// ===== GENERATED by scripts/build-workflows.js from src/ - edit src/, then `npm run build` =====\n';
  return header + modules.map(([f, n]) => inlineModule(f, n)).join('\n') + '\n// ===== node logic =====\n' + body.trim() + '\n';
}

module.exports = { inlineModule, codeNode };
