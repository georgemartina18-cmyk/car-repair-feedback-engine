// Writes supabase/seed.sql from the sample data, so the database starts
// with the same categories, sample products and delivery fees as the demo.
// Run with: npm run samples

import { writeFileSync } from 'node:fs';
import { DEFAULT_SETTINGS } from '../src/config/defaults.ts';
import { SAMPLE_BANNERS, SAMPLE_BRANDS, SAMPLE_CATEGORIES, SAMPLE_PRODUCTS } from '../src/data/samples.ts';
import { DEFAULT_DELIVERY_ZONES } from '../src/data/states.ts';

const q = (v) => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number' || typeof v === 'boolean') return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
};
const arr = (a) => `array[${a.map(q).join(',')}]::text[]`;
const json = (v) => `${q(JSON.stringify(v))}::jsonb`;

const out = [];
out.push('-- Sample data for Gadgets Store in Lagos. Safe to run more than once.');
out.push('-- Generated by scripts/make-seed-sql.mjs. Do not edit by hand.\n');

const s = DEFAULT_SETTINGS;
const settingsCols = Object.keys(s);
out.push(`insert into settings (id, ${settingsCols.join(', ')}) values (1, ${settingsCols.map((k) => q(s[k])).join(', ')}) on conflict (id) do nothing;\n`);

for (const c of SAMPLE_CATEGORIES) {
  out.push(`insert into categories (slug, name, description, icon, sort_order) values (${[c.slug, c.name, c.description, c.icon, c.sort_order].map(q).join(', ')}) on conflict (slug) do nothing;`);
}
out.push('');
for (const b of SAMPLE_BRANDS) {
  out.push(`insert into brands (slug, name) values (${q(b.slug)}, ${q(b.name)}) on conflict (slug) do nothing;`);
}
out.push('');
for (const z of DEFAULT_DELIVERY_ZONES) {
  out.push(`insert into delivery_zones (state, fee, eta) values (${q(z.state)}, ${z.fee}, ${q(z.eta)}) on conflict (state) do nothing;`);
}
out.push('');
out.push('-- Banners (only added if there are none yet)');
out.push('do $$ begin if not exists (select 1 from banners) then');
for (const b of SAMPLE_BANNERS) {
  out.push(`  insert into banners (title, subtitle, cta_label, cta_link, image, theme, sort_order) values (${[b.title, b.subtitle, b.cta_label, b.cta_link, b.image, b.theme, b.sort_order].map(q).join(', ')});`);
}
out.push('end if; end $$;\n');

out.push('-- Sample products (is_sample = true, so they can all be deleted at once later)');
for (const p of SAMPLE_PRODUCTS) {
  const cols = 'slug, name, brand, category, short_description, description, price, compare_at_price, condition, stock, featured, colors, storage_options, specs, images, warranty, is_sample, created_at';
  const vals = [
    q(p.slug), q(p.name), q(p.brand), q(p.category), q(p.short_description), q(p.description),
    q(p.price), q(p.compare_at_price), q(p.condition), q(p.stock), q(p.featured),
    arr(p.colors), json(p.storage_options), json(p.specs), arr(p.images), q(p.warranty), 'true', q(p.created_at),
  ].join(', ');
  out.push(`insert into products (${cols}) values (${vals}) on conflict (slug) do nothing;`);
}

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), out.join('\n') + '\n');
console.log('Wrote supabase/seed.sql');
